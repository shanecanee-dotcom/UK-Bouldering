"""Generate data/history.js: first ascents of boulder problems from climbing-history.org.

Run from the project root:

    python3 tools/build_history.py

One request per crag (the crag page's ascents table), spaced out to be polite.
Only boulder problems with a recorded first ascent are kept. The app links back to
climbing-history.org for each one; their data is © climbing-history.org contributors.
Uses curl for HTTP because the macOS system Python's SSL is too old for some hosts.
"""
import html, json, re, subprocess, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UA = "Mozilla/5.0 (uk-boulders first-ascent importer)"
BASE = "https://climbing-history.org"

# Our crag id → climbing-history.org crag path (matched by position against their crag map)
CRAGS = {
    "stanage-plantation": "/crag/101/stanage", "burbage-north": "/crag/88/burbage-north-and-west",
    "burbage-south": "/crag/89/burbage-south", "curbar": "/crag/21/curbar-edge",
    "froggatt": "/crag/22/froggatt-edge", "the-roaches": "/crag/105/the-roaches",
    "almscliff": "/crag/373/almscliff", "caley": "/crag/540/caley-crags", "brimham": "/crag/538/brimham-rocks",
    "bowderstone": "/crag/2282/the-bowderstone", "cromlech-boulders": "/crag/1635/cromlech-boulders",
    "dumbarton": "/crag/189/dumbarton-rock", "bowden-doors": "/crag/824/bowden-doors",
    "hound-tor": "/crag/224/hound-tor", "harrisons": "/crag/57/harrisons-rocks", "ilkley": "/crag/547/ilkley",
    "shipley-glen": "/crag/1343/shipley-glen", "robin-hoods-stride": "/crag/926/robin-hoods-stride",
    "kyloe-in-the-wood": "/crag/838/kyloe-in-the-woods", "langdale-boulders": "/crag/354/langdale-boulders",
    "porth-ysgo": "/crag/1368/porth-ysgo", "bonehill": "/crag/292/bonehill-rocks",
}


def get(url):
    return subprocess.run(["curl", "-s", "-m", "60", "-A", UA, url], capture_output=True, text=True).stdout


def clean(fragment):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", fragment))).strip()


def font_grade(g):
    g = g.strip().upper().replace("FONT ", "").replace("F", "")
    return "f" + g if re.fullmatch(r"\d[ABC]?\+?", g) else None


def parse(page):
    """Rows of the ascents table, each followed by an optional subtitle row ('First ascent.' etc.)."""
    rows = re.findall(r'<tr class="ascent[^"]*"[^>]*>(.*?)</tr>', page, re.S)
    out, last = [], None
    for row in rows:
        sub = re.search(r'class="ascent-subtitle[^"]*">(.*?)</small>', row, re.S)
        if sub:
            if last is not None:
                last["note"] = clean(sub.group(1))
            continue
        cells = re.findall(r"<td[^>]*>(.*?)</td>", row, re.S)
        climb = re.search(r'<a href="(/climb/[^"]+)">(.*?)</a>', row, re.S)
        if len(cells) < 7 or not climb:
            last = None
            continue
        climber_link = re.search(r'<a href="(/climber/[^"]+)">', cells[4])
        last = {
            "name": clean(climb.group(2)),
            "url": BASE + climb.group(1),
            "grade": clean(cells[3]),
            "climber": clean(cells[4]),
            "climberUrl": BASE + climber_link.group(1) if climber_link else None,
            "style": clean(cells[5]),
            "date": clean(cells[6]) or clean(cells[0]),
            "note": "",
        }
        out.append(last)
    return out


def main():
    result = {}
    for area_id, path in CRAGS.items():
        rows = parse(get(BASE + path))
        time.sleep(1.5)
        fas, seen = [], set()
        for r in rows:
            if not r["style"].lower().startswith("boulder") or "first ascent" not in r["note"].lower():
                continue
            g = font_grade(r["grade"])
            if not g or r["name"].lower() in seen:
                continue
            seen.add(r["name"].lower())
            fas.append({k: r[k] for k in ("name", "url", "climber", "climberUrl", "date")} | {"grade": g})
        result[area_id] = {"url": BASE + path, "firstAscents": fas}
        print(f"{area_id:<20} {len(rows):>4} ascents listed  {len(fas):>3} boulder first ascents")

    header = (
        "// GENERATED by tools/build_history.py – do not edit by hand.\n"
        "// First ascents of boulder problems from climbing-history.org (© climbing-history.org contributors).\n"
        f"// Generated {time.strftime('%Y-%m-%d')}.\n"
    )
    (ROOT / "data/history.js").write_text(header + "export const HISTORY = " + json.dumps(result, ensure_ascii=False, indent=1) + ";\n")
    print("wrote data/history.js")


if __name__ == "__main__":
    main()
