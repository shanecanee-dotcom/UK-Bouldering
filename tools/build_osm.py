"""Generate data/osm.js: boulders and boulder problems mapped in OpenStreetMap near each crag.

Run from the project root (after adding crags, or to pick up new OSM edits):

    python3 tools/build_osm.py

OpenStreetMap data © OpenStreetMap contributors, available under the ODbL.
The app merges this with data/areas.js: new problems are added, existing ones gain exact
positions, and named boulders appear on the map.
Uses curl for HTTP because the macOS system Python's SSL is too old for Overpass.
"""
import json, math, re, subprocess, time, urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UA = "uk-boulders-osm/0.1 (static site generator)"
RADIUS = 1200  # metres around each crag pin
OVERPASS = "https://overpass-api.de/api/interpreter"


def metres(a, b):
    lat = math.radians((a[0] + b[0]) / 2)
    return math.hypot((b[1] - a[1]) * 111320 * math.cos(lat), (b[0] - a[0]) * 110540)


def parse_areas():
    src = (ROOT / "data/areas.js").read_text()
    out = []
    for m in re.finditer(r'\n  \{\n    id: "([^"]+)",\n    name: "([^"]+)",.*?\n    lat: ([-\d.]+), lng: ([-\d.]+),', src, re.S):
        out.append({"id": m.group(1), "name": m.group(2), "lat": float(m.group(3)), "lng": float(m.group(4))})
    return out


def overpass(areas):
    parts = "".join(
        f'nwr(around:{RADIUS},{a["lat"]},{a["lng"]})[sport=climbing][name];'
        f'nwr(around:{RADIUS},{a["lat"]},{a["lng"]})["climbing:boulder"][name];'
        for a in areas
    )
    q = f"[out:json][timeout:120];({parts});out center tags;"
    for attempt in range(6):
        r = subprocess.run(
            ["curl", "-s", "-m", "180", "-A", UA, "--data-urlencode", f"data={q}", OVERPASS],
            capture_output=True, text=True,
        )
        if r.stdout.startswith("{"):
            return json.loads(r.stdout)["elements"]
        wait = 15 * (attempt + 1)
        print(f"Overpass busy, retrying in {wait}s")
        time.sleep(wait)
    raise RuntimeError("Overpass kept failing")


def is_boulder(t):
    """A named boulder or block (not a whole crag/edge or a single route)."""
    c = t.get("climbing")
    if c == "boulder":
        return True
    if t.get("climbing:boulder") == "yes" and c in (None, "crag"):
        return not re.search(r"\b(edge|tier|crags?|rocks|area)\b", t.get("name", ""), re.I)
    return False


def is_problem(t):
    """A single boulder problem: a route tagged as bouldering or with a boulder grade."""
    if t.get("climbing") not in ("route_bottom", "route"):
        return False
    return t.get("climbing:boulder") == "yes" or "climbing:grade:font" in t or "climbing:grade:hueco" in t


def grade_of(t):
    font = t.get("climbing:grade:font") or t.get("climbing:grade:fontainebleau")
    if font:
        g = font.strip().upper().replace("F", "")
        return "f" + g if re.fullmatch(r"\d[ABC]?\+?", g) else None
    hueco = t.get("climbing:grade:hueco")
    if hueco:
        g = hueco.strip().upper().split("/")[0]  # "V2/V3" → "V2"
        return g if re.fullmatch(r"V(B|\d{1,2}[+-]?)", g) else None
    return None


def main():
    areas = parse_areas()
    els = overpass(areas)

    # Crags can be close together (e.g. Burbage North/South): give each feature to its nearest crag
    owner = {}
    for e in els:
        p = e.get("center", e)
        pos = (p["lat"], p["lon"])
        best = min(areas, key=lambda a: metres((a["lat"], a["lng"]), pos))
        if metres((best["lat"], best["lng"]), pos) <= RADIUS:
            owner.setdefault(best["id"], []).append((e["tags"], pos))

    result = {}
    for a in areas:
        near = owner.get(a["id"], [])

        boulders = {}
        for t, pos in near:
            if is_boulder(t) and t["name"] != a["name"]:
                boulders.setdefault(t["name"], {"lat": round(pos[0], 6), "lng": round(pos[1], 6)})

        problems, seen = [], set()
        for t, pos in near:
            if not is_problem(t):
                continue
            g = grade_of(t)
            key = (t["name"].lower(), g)
            if not g or key in seen:
                continue
            seen.add(key)
            # Attach to the nearest named boulder within 30 m, if any
            nb = min(boulders.items(), key=lambda kv: metres(pos, (kv[1]["lat"], kv[1]["lng"])), default=None)
            boulder = nb[0] if nb and metres(pos, (nb[1]["lat"], nb[1]["lng"])) <= 30 else None
            prob = {"name": t["name"], "grade": g, "lat": round(pos[0], 6), "lng": round(pos[1], 6)}
            if boulder:
                prob["boulder"] = boulder
            problems.append(prob)

        if boulders or problems:
            result[a["id"]] = {"boulders": boulders, "problems": problems}
        print(f'{a["id"]:<20} boulders {len(boulders):>3}  problems {len(problems):>3}')

    header = (
        "// GENERATED by tools/build_osm.py – do not edit by hand.\n"
        "// Boulders and problems mapped in OpenStreetMap. © OpenStreetMap contributors, ODbL.\n"
        f"// Generated {time.strftime('%Y-%m-%d')}.\n"
    )
    (ROOT / "data/osm.js").write_text(header + "export const OSM = " + json.dumps(result, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("wrote data/osm.js")


if __name__ == "__main__":
    main()
