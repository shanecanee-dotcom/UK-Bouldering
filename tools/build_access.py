"""Generate data/access.js: access status, parking notes and parking locations from the
BMC Regional Access Database (RAD), https://www.thebmc.co.uk/rad

Run from the project root:

    python3 tools/build_access.py

RAD covers England and Wales only. The app shows this information with a link back to each
crag's RAD page, which is always the up-to-date source. Requests are spaced out to be polite.
Uses curl for HTTP because the macOS system Python's SSL is too old for some hosts.
"""
import html, json, re, subprocess, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UA = "Mozilla/5.0 (uk-boulders access importer)"
BASE = "https://services.thebmc.co.uk"

# Our crag id → RAD crag id (checked by name and position against RAD's crag list)
RAD_IDS = {
    "stanage-plantation": 150, "burbage-north": 550, "burbage-south": 551, "curbar": 549,
    "froggatt": 587, "the-roaches": 314, "almscliff": 465, "caley": 382, "brimham": 752,
    "bowderstone": 4901, "cromlech-boulders": 2562, "bowden-doors": 545, "hound-tor": 3437,
    "harrisons": 119, "ilkley": 486, "shipley-glen": 492, "robin-hoods-stride": 4457,
    "kyloe-in-the-wood": 546, "langdale-boulders": 883, "porth-ysgo": 4324, "bonehill": 1867,
}


def curl(*args):
    r = subprocess.run(["curl", "-s", "-m", "60", "-A", UA, *args], capture_output=True, text=True)
    return r.stdout


def text(fragment):
    t = html.unescape(re.sub(r"<[^>]+>", " ", fragment))
    return re.sub(r"\s+", " ", t).strip()


def field(page, label):
    m = re.search(re.escape(label) + r":\s*</[^>]+>\s*<[^>]+>([^<]*)<", page)
    return m.group(1).strip() if m else None


def main():
    crags = json.loads(curl("-X", "POST", "-H", "Content-Type: application/json; charset=utf-8", "-d", "{}",
                            f"{BASE}/Services/MapService.asmx/LoadCrags"))["d"]
    by_id = {c["Id"]: c for c in crags}
    out = {}
    for area_id, rad in RAD_IDS.items():
        c = by_id[f"c{rad}"]
        page = curl(f"{BASE}/modules/RAD/View.aspx?id={rad}")
        time.sleep(1.5)

        parking = re.search(r'<div id="parking" class="crag-restrictions">(.*?)</div>', page, re.S)
        parking_note = None
        if parking:
            paras = re.findall(r"<p>(.*?)</p>", parking.group(1), re.S)
            parking_note = " ".join(text(p) for p in paras) or None

        spots = [
            {"title": t.strip() or "Parking", "lat": round(float(la), 6), "lng": round(float(lo), 6)}
            for t, la, lo, icon in re.findall(
                r"markers\.push\(\{ title: '([^']*)', latlng: \{ lat: (-?[\d.]+), lng: (-?[\d.]+)\}, icon: '([^']*)'", page)
            if icon == "parking"
        ]
        updated = re.search(r"Last updated:\s*([\d/]+)", page)
        summary = re.search(r'<p class="crag-header__summary">(.*?)</p>', page, re.S)

        out[area_id] = {
            "radId": rad,
            "name": c["Title"],
            "url": f"https://www.thebmc.co.uk/modules/RAD/View.aspx?id={rad}",
            "light": c["Light"],
            "restricted": bool(c["IsInRestriction"]),
            "gridRef": (c.get("GridRef") or "").replace(" ", "") or None,
            "crow": field(page, "CRoW Land"),
            "owner": field(page, "Ownership"),
            "developed": field(page, "Year Developed") or None,
            "parkingNote": parking_note,
            "parkingSpots": spots,
            "updated": updated.group(1) if updated else None,
        }
        o = out[area_id]
        print(f'{area_id:<20} {o["light"]:<6}{" RESTRICTED" if o["restricted"] else "":<11} parking spots {len(spots)}  '
              f'CRoW {o["crow"]}  updated {o["updated"]}  note: {(parking_note or "-")[:60]}')

    header = (
        "// GENERATED by tools/build_access.py – do not edit by hand.\n"
        "// Access information from the BMC Regional Access Database (https://www.thebmc.co.uk/rad).\n"
        "// Always check the linked RAD page before you go: access can change at short notice.\n"
        f"// Generated {time.strftime('%Y-%m-%d')}.\n"
    )
    (ROOT / "data/access.js").write_text(header + "export const ACCESS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
    print("wrote data/access.js")


if __name__ == "__main__":
    main()
